/** Returns the pose for (buddy, state, tickMs). */
function frameFor(buddy, state, tickMs) {
  const s = buddy[state] || buddy.idle;
  const idx = cycle(tickMs, s.beatMs, s.seq);
  return s.poses[idx];
}

/** Returns a multiline string ready to drop into a <pre>. */
function renderFrame(buddy, state, tickMs) {
  return frameFor(buddy, state, tickMs).join("\n");
}

/** Returns the overlay kind for (buddy, state) or null. */
function overlayFor(buddy, state) {
  const s = buddy[state];
  return (s && s.overlay) || null;
}

