// ASCII buddy frame tables + state sequences, ported from the ESP32
// firmware in ../../src/buddies/*.cpp.
//
// Every species declares 7 states (sleep, idle, busy, attention,
// celebrate, dizzy, heart). Each state has:
//   - poses: N frames, 5 lines each
//   - seq:   which pose plays at each beat
//   - beatMs: how many ms per beat
// Overlays (particles) are declared separately per state and rendered
// on a second absolutely-positioned layer in the DOM.

// All sprites are normalized to W columns wide so the <pre> stays a
// fixed grid. The firmware uses pixel-precise x-offsets for wider
// poses; in a browser we just pad/truncate to one width.
const W = 14;

function normalize(line) {
  if (line.length === W) return line;
  if (line.length > W) return line.slice(0, W);
  const pad = W - line.length;
  const left = Math.floor(pad / 2);
  return " ".repeat(left) + line + " ".repeat(pad - left);
}

function sprite(lines) {
  return lines.map(normalize);
}

function cycle(t, beatMs, seq) {
  return seq[Math.floor(t / beatMs) % seq.length];
}

